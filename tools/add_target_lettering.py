def facet(normal, a, b, c):
    return (
        f"  facet normal {normal[0]:.7f} {normal[1]:.7f} {normal[2]:.7f}\n"
        "    outer loop\n"
        f"      vertex {a[0]:.5f} {a[1]:.5f} {a[2]:.5f}\n"
        f"      vertex {b[0]:.5f} {b[1]:.5f} {b[2]:.5f}\n"
        f"      vertex {c[0]:.5f} {c[1]:.5f} {c[2]:.5f}\n"
        "    endloop\n"
        "  endfacet\n"
    )


def cuboid(x0, y0, z0, x1, y1, z1):
    p000, p100, p110, p010 = (x0,y0,z0), (x1,y0,z0), (x1,y1,z0), (x0,y1,z0)
    p001, p101, p111, p011 = (x0,y0,z1), (x1,y0,z1), (x1,y1,z1), (x0,y1,z1)
    faces = [
        ((0,0,-1), p000,p110,p100), ((0,0,-1), p000,p010,p110),
        ((0,0,1), p001,p101,p111), ((0,0,1), p001,p111,p011),
        ((0,-1,0), p000,p100,p101), ((0,-1,0), p000,p101,p001),
        ((1,0,0), p100,p110,p111), ((1,0,0), p100,p111,p101),
        ((0,1,0), p110,p010,p011), ((0,1,0), p110,p011,p111),
        ((-1,0,0), p010,p000,p001), ((-1,0,0), p010,p001,p011),
    ]
    return "".join(facet(*face) for face in faces)


def text_mesh(text, x, y, cell=0.85, depth=0.6, z=3.2):
    pixel = cell * 0.9
    advance = cell * 6
    out = []
    for char_index, char in enumerate(text):
        glyph = FONT[char]
        for row, line in enumerate(glyph):
            for col, filled in enumerate(line):
                if filled == "1":
                    px = x + char_index * advance + col * cell
                    py = y + (6 - row) * cell
                    out.append(cuboid(px, py, z, px + pixel, py + pixel, z + depth))
    return "".join(out)


def add_lettering(path: Path):
    source = path.read_text(encoding="ascii")
    source = re.sub(r"\s*solid boprc_fixed_lettering.*?endsolid boprc_fixed_lettering\s*", "\n", source, flags=re.S)
    lettering = [
        "solid boprc_fixed_lettering\n",
        text_mesh("BOPRC SURVEY CONTROL", 175.0, 158.0),
        text_mesh("PLEASE DO NOT REMOVE", 175.0, 146.0),
        text_mesh("0800 884 880", 175.0, 134.0),
        "endsolid boprc_fixed_lettering\n",
    ]
    path.write_text(source.rstrip() + "\n" + "".join(lettering), encoding="ascii", newline="\n")


